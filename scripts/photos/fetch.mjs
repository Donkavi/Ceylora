// Downloads selected Commons photos, resizes them, and writes the typed photo registry.
// Usage: node fetch.mjs <selection.json> <candidates.json> <projectRoot>
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const [, , selPath, candPath, root] = process.argv;
const require = createRequire(path.join(root, 'package.json'));
const sharp = require('sharp');

const UA = 'CeyloraImageSourcing/1.0 (static site build script)';
const sel = JSON.parse(fs.readFileSync(selPath, 'utf8'));
const cands = JSON.parse(fs.readFileSync(candPath, 'utf8'));
const imgDir = path.join(root, 'public', 'images');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(url) {
  for (let a = 0; a < 7; a++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    if (res.status === 429 || res.status >= 500) { await sleep(5000 * (a + 1)); continue; }
    throw new Error(`${res.status} ${url}`);
  }
  throw new Error(`retries exhausted ${url}`);
}

function urls(thumb) {
  const clean = thumb.split('?')[0];
  const m = clean.match(/^(https:\/\/[^/]+)\/wikipedia\/commons\/thumb\/(.+)\/(\d+)px-[^/]+$/);
  if (!m) throw new Error(`unexpected thumb url ${clean}`);
  const original = `https://upload.wikimedia.org/wikipedia/commons/${m[2]}`;
  return { at: (w) => clean.replace(/\/\d+px-/, `/${w}px-`), original };
}

const cleanAuthor = (s) =>
  s.replace(/\s*\(talk\)/gi, '').replace(/^User:/, '').replace(/\s+/g, ' ').trim().slice(0, 80) || 'Unknown';

const registryPath = path.join(root, 'src', 'data', 'photos.generated.ts');
const existing = new Map();
if (fs.existsSync(registryPath)) {
  const m = fs.readFileSync(registryPath, 'utf8').match(/= (\[[\s\S]*\]);/);
  if (m) for (const p of JSON.parse(m[1])) existing.set(p.id, p);
}

const out = [];
for (const [topic, picks] of Object.entries(sel)) {
  for (const [idx, id, alt, focus] of picks) {
    const c = cands[topic]?.[idx];
    if (!c) { console.error('missing candidate', topic, idx); continue; }
    const group = topic;
    const dir = path.join(imgDir, group);
    const file = path.join(dir, `${id}.jpg`);
    const prev = existing.get(id);
    if (prev && fs.existsSync(file) && prev.credit.source === c.page) {
      out.push({ ...prev, alt, ...(focus ? { focus } : {}) });
      continue;
    }
    fs.mkdirSync(dir, { recursive: true });
    const isHero = /-hero$/.test(id) || id.startsWith('home-') || id.startsWith('journey-');
    const target = isHero ? 2560 : 1920;
    const u = urls(c.thumb);
    let src;
    if (c.width > 3840 && isHero) src = u.at(3840);
    else if (c.width > 1920) src = u.at(1920);
    else if (c.width > 1280) src = u.at(1280);
    else src = u.original;
    try {
      const buf = await get(src);
      const img = sharp(buf).rotate().resize({ width: target, withoutEnlargement: true });
      const { data, info } = await img.jpeg({ quality: 82, mozjpeg: true, progressive: true }).toBuffer({ resolveWithObject: true });
      fs.writeFileSync(file, data);
      const blurBuf = await sharp(data).resize(24).jpeg({ quality: 45 }).toBuffer();
      out.push({
        id,
        src: `/images/${group}/${id}.jpg`,
        width: info.width,
        height: info.height,
        alt,
        blur: `data:image/jpeg;base64,${blurBuf.toString('base64')}`,
        credit: { author: cleanAuthor(c.artist), license: c.license || 'See source', source: c.page },
        ...(focus ? { focus } : {}),
      });
      console.log('ok', id, info.width, 'x', info.height, Math.round(data.length / 1024) + 'KB');
    } catch (e) {
      console.error('FAIL', id, e.message);
    }
    await sleep(400);
  }
}

const header = `// Generated by the image sourcing script — real photographs from Wikimedia Commons.\n// Each entry carries its author, licence and source page for attribution.\nimport type { Photo } from '@/types';\n\n`;
fs.writeFileSync(registryPath, `${header}export const photoList: Photo[] = ${JSON.stringify(out, null, 2)};\n`);
console.log('registry', out.length);
